// Package session — чистые расчёты сессии ПК без БД: возврат при досрочном завершении
// (SessionSettlement), продление сессии покупкой, естественное истечение, запуск сохранённого
// пакета, пересадка на другой ПК.
//
// Функции принимают снимок данных (части оплаты сессии, поля сессии ПК, пакет) и текущее время,
// а возвращают план: сколько вернуть на каждый баланс, какие пакеты создать, какие строки удалить,
// на сколько уменьшить накопительные траты. Исполняет план (ledger, bonus/loyalty, sqlc) вызывающий
// слой в одной транзакции — так же, как старый код делал всё внутри DB::transaction.
//
// Время. Старый код хранил даты в MySQL `timestamp`/`datetime` без долей секунды: Eloquent пишет их
// форматом `Y-m-d H:i:s`, то есть доли секунды ОТБРАСЫВАЮТСЯ (не округляются). Postgres `timestamptz`
// хранит микросекунды, поэтому всё, что этот пакет предлагает сохранить, уже усечено до секунды
// (StoredTime). Сравнения «в будущем?» (Carbon isFuture/gt) старый код делал с полной точностью now()
// против усечённого значения из БД — здесь так же (time.Time.After). Разности «сколько секунд осталось»
// старый код считал через getTimestamp() (целые секунды Unix, доли отброшены у обоих операндов) — здесь
// через time.Time.Unix().
//
