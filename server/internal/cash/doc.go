// Package cash — касса: смены, продажи POS, пополнение баланса клиента на кассе, приход/расход,
// возвраты по чеку и X/Z-отчёты (BR-050…BR-057, BR-060).
//
// Этот слой — ЧИСТЫЕ расчёты и правила без БД: функции получают уже прочитанные данные (смену, операции
// смены, товары, балансы) и возвращают, что записать (суммы в тиынах, строки чека, движения склада, ошибки
// с текстами старого кода). Подключение к ledger и БД (блокировки FOR UPDATE, порядок блокировок BR-005,
// ключи идемпотентности) — следующий шаг.
//
// Деньги. Старая касса считала во float и полагалась на округление MySQL decimal(…,2) при записи
// (Laravel: app/Services/CashRegisterService.php; BR-001, BR-052…BR-054). Здесь это повторено буквально
// через пакет money:
//   - пополнение и начальный остаток смены приводились к (float) — money.ParseTengeViaFloat;
//   - приход/расход передавал строку запроса в create() — money.ParseTengeRounded;
//   - сумма продажи — float-сумма (float)price*qty — money.FromTengeFloatDecimal;
//   - сравнения «в кассе недостаточно средств» — float против float, как в PHP (см. Totals.BalanceFloat).
//
// Допущения Этапа 1: Q-002 (касса округляет как MySQL), Q-013 (payment_method — необязательное поле,
