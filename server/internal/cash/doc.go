// Package cash — касса: смены, продажи POS, пополнение баланса клиента на кассе, приход/расход,
// возвраты по чеку и X/Z-отчёты (BR-050…BR-057, BR-060).
//
// Этот слой — ЧИСТЫЕ расчёты и правила без БД: функции получают уже прочитанные данные (смену, операции
// смены, товары, балансы) и возвращают, что записать (суммы в тиынах, строки чека, движения склада, ошибки
// с текстами старого кода). Подключение к ledger и БД (блокировки FOR UPDATE, порядок блокировок BR-005,
// ключи идемпотентности) — следующий шаг.
//
// Деньги. Старая касса считала во float и полагалась на округление MySQL decimal(…,2) при записи
// (Laravel: app/Services/CashRegisterService.php; BR-001, BR-052…BR-054).
// Решение Q-002, CQ-3 (docs/DECISIONS.md): здесь всё — в целых тиынах:
//   - суммы из форм (пополнение, приход/расход, начальный остаток) разбираются строго (money.ParseTenge):
//     > 2 знаков после точки — ошибка decimal (422), а не округление;
//   - сумма продажи — точно Σ price × qty;
//   - «в кассе недостаточно средств» и closing_balance — точно, без float.
//
// Для корректного ввода (≤ 2 знаков) суммы те же, что в старом коде. Отчёты X/Z повторяют float-пути старого
// кода только в показе (сортировка, «прочий приход»), см. report.go.
//
// Допущения Этапа 1: Q-013 (payment_method — необязательное поле,
// в остатке смены и отчётах не используется), Q-007/BR-160 (вид прихода для отчёта — входной параметр,
// а не журнал действий).
