// BC-07: number_format PHP — одна реализация вместо шести копий (cash, httpx, billing, http/legacy, superadmin,
// clubmap). До объединения вывод каждой копии сверен с этой функцией побайтно на 260 значениях (границы групп,
// отрицательные, MaxInt64, MinInt64+1) и всех разделителях, которыми они вызывались.
func TestNumberFormat(t *testing.T) {
	cases := []struct {
		t        Tiyn
		dec, sep string
		want     string
	}{
		{0, ",", " ", "0,00"},
		{1, ",", " ", "0,01"},
		{-1, ",", " ", "-0,01"},
		{-50, ".", " ", "-0.50"},
		{99, ".", " ", "0.99"},
		{100, ".", " ", "1.00"},
		{99999, ",", " ", "999,99"},
		{100000, ",", " ", "1 000,00"},
		{210000, ",", " ", "2 100,00"}, // «Возврат проведён: 2 100,00 KZT выданы из кассы.»
		{150050, ".", " ", "1 500.50"},
		{-150000, ".", " ", "-1 500.00"},
		{-1200, ".", " ", "-12.00"},
		{123456789, ".", " ", "1 234 567.89"},
		{123456789, ",", " ", "1 234 567,89"},
		{123456789, ".", ",", "1,234,567.89"},
		{123456789, ".", "", "1234567.89"},
		{123456789, ",", " ", "1 234 567,89"},
		{-123456789, ".", "", "-1234567.89"},
		{99_999_999_999_999, ",", " ", "999 999 999 999,99"},
		{MaxAmount, ".", " ", "10 000 000 000 000.00"},
		{-MaxAmount, ".", " ", "-10 000 000 000 000.00"},
		{math.MaxInt64, ".", " ", "92 233 720 368 547 758.07"},
		{math.MinInt64, ".", " ", "-92 233 720 368 547 758.08"},
	}
	for _, c := range cases {
		if got := NumberFormat(c.t, c.dec, c.sep); got != c.want {
			t.Errorf("NumberFormat(%d, %q, %q) = %q, want %q", int64(c.t), c.dec, c.sep, got, c.want)
		}
	}
	// Без разделителя групп и с точкой — то же, что Tenge().
	for _, v := range []Tiyn{0, 5, -5, 99, 100, -100, 123456, -123456, MaxAmount, math.MaxInt64, math.MinInt64} {
		if got := NumberFormat(v, ".", ""); got != v.Tenge() {
			t.Errorf("NumberFormat(%d) = %q, Tenge = %q", int64(v), got, v.Tenge())
		}
	}
}

func TestGroupThousands(t *testing.T) {
	cases := []struct {
		n    int64
		sep  string
		want string
	}{
		{0, ",", "0"},
		{7, ",", "7"},
		{-7, ",", "-7"},
		{999, ",", "999"},
		{-999, ",", "-999"},
		{1000, ",", "1,000"},
		{-1000, " ", "-1 000"},
		{16384, ",", "16,384"}, // «16,384 MB RAM»
		{1234567, " ", "1 234 567"},
		{1234567, "", "1234567"},
		{100000, " ", "100 000"},
		{math.MaxInt64, ",", "9,223,372,036,854,775,807"},
		{math.MinInt64, ",", "-9,223,372,036,854,775,808"},
	}
	for _, c := range cases {
		if got := GroupThousands(c.n, c.sep); got != c.want {
			t.Errorf("GroupThousands(%d, %q) = %q, want %q", c.n, c.sep, got, c.want)
		}
	}
}
