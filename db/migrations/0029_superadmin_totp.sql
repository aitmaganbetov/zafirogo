-- Этап 7: второй фактор входа суперадмина — TOTP (RFC 6238) и одноразовые коды восстановления
-- (docs/security-review.md SEC-010, docs/open-questions/stage7-totp.md). В старом Laravel этого нет — новая функция
-- по поручению владельца.
--
-- superadmin_totp — ключ TOTP суперадмина:
--   * secret — только шифротекст secretbox (v2:<kid>:…, контекст superadmin_totp.secret:user=<user_id>,
--     ключи security.data_keys); перешифровку при ротации ключей делает воркер reencrypt-secrets;
--   * confirmed_at — NULL, пока суперадмин не ввёл первый код (настройка не завершена);
--   * last_step — последний принятый шаг TOTP (unix / 30): тот же код повторно не принимается.
-- superadmin_recovery_codes — 10 одноразовых кодов восстановления: только sha256 (у кода 80 бит случайности),
-- used_at — когда использован.
--
-- Права: только пул платформы zafiro_platform (вход суперадмина, кабинет, воркер). Пул клуба zafiro_app таблиц не
-- видит вовсе: ошибка в любом запросе клуба не должна выдать или сбросить второй фактор суперадмина (как SEC-005).

-- +goose Up
CREATE TABLE superadmin_totp (
    user_id      bigint PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    secret       text        NOT NULL CONSTRAINT superadmin_totp_secret_sealed CHECK (secret ~ '^v[0-9]+:'),
    confirmed_at timestamptz,
    last_step    bigint      NOT NULL DEFAULT 0,
    created_at   timestamptz NOT NULL,
    updated_at   timestamptz NOT NULL
);

COMMENT ON TABLE superadmin_totp IS 'TOTP суперадмина (RFC 6238, SHA-1, 6 цифр, 30 с); только пул zafiro_platform';
COMMENT ON COLUMN superadmin_totp.secret IS
    'Ключ TOTP, зашифрован secretbox (v2:<kid>:…, контекст superadmin_totp.secret:user=<user_id>)';
COMMENT ON COLUMN superadmin_totp.last_step IS 'Последний принятый шаг TOTP: повтор того же кода отклоняется';

CREATE TABLE superadmin_recovery_codes (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    code_hash  text        NOT NULL,
    used_at    timestamptz,
    created_at timestamptz NOT NULL,
    CONSTRAINT superadmin_recovery_codes_unique UNIQUE (user_id, code_hash)
);

COMMENT ON TABLE superadmin_recovery_codes IS 'Одноразовые коды восстановления суперадмина (sha256); только пул zafiro_platform';

REVOKE ALL ON superadmin_totp, superadmin_recovery_codes FROM zafiro_app;
REVOKE ALL ON SEQUENCE superadmin_recovery_codes_id_seq FROM zafiro_app;
REVOKE ALL ON superadmin_totp, superadmin_recovery_codes FROM zafiro_platform;
GRANT SELECT, INSERT, UPDATE, DELETE ON superadmin_totp, superadmin_recovery_codes TO zafiro_platform;
GRANT USAGE, SELECT ON SEQUENCE superadmin_recovery_codes_id_seq TO zafiro_platform;

-- +goose Down
DROP TABLE superadmin_recovery_codes;
DROP TABLE superadmin_totp;
