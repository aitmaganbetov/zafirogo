-- 0024_mobile_api_tokens: токены мобильных приложений Flutter (mobileclient, mobileemployee) в формате Sanctum.
-- Решение Q-058 (docs/DECISIONS.md): приложения не меняются, клуб переезжает на новый сервер — слой совместимости
-- со старым REST (server/internal/http/legacy, описание — docs/mobile-compat.md).
--
-- Laravel: таблица personal_access_tokens (laravel/sanctum v4.3.3): приложение получает «<id>|<токен>»,
-- в БД — sha256(токен) hex в колонке token, ability "club:<id>" (токен одного клуба), expires_at = +30 дней
-- (AuthController::issueUserLoginResponse(), switchClub()), last_used_at обновляется при запросе.
--
-- Здесь то же самое, кроме:
--   * клуб токена — колонка club_id (вместо ability "club:<id>"), RLS как у всех тенантных таблиц;
--   * выход и смена клуба не удаляют строку, а ставят revoked_at: по id сервер узнаёт «свой» токен и не
--     отправляет его на старый сервер (маршрутизация по клубу при поклубном переходе, docs/mobile-compat.md §3);
--   * id перенесённых токенов — те же, что в personal_access_tokens (иначе «<id>|…» в телефоне перестанет
--     работать), новые токены выдаются с 10^12, чтобы не пересечься с id старой БД клубов, переезжающих позже.
--
-- Поиск токена при запросе (клуб ещё не известен) — как у кодов регистрации ПК (0009): транзакция ставит
-- app.mobile_token_hash = sha256 hex и видит ТОЛЬКО строку с этим хешем (политика mobile_token_lookup, SELECT).
-- Знать хеш = знать токен. Отзыв всех токенов аккаунта (сброс пароля: $user->tokens()->delete()) — политика
-- mobile_token_owner по app.user_id.

-- +goose Up

CREATE TABLE mobile_api_tokens (
    id           bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000000) PRIMARY KEY,
    club_id      bigint NOT NULL,
    user_id      bigint NOT NULL,
    -- device_name запроса входа («mobileclient», «Zafiro Staff»; видно в журнале входов).
    name         varchar(255) NOT NULL,
    -- sha256(часть после «|») в hex, как personal_access_tokens.token.
    token_hash   char(64) NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz,
    expires_at   timestamptz,
    revoked_at   timestamptz,
    CONSTRAINT mobile_api_tokens_token_hash_unique UNIQUE (token_hash),
    CONSTRAINT mobile_api_tokens_token_hash_check CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT mobile_api_tokens_club_id_foreign FOREIGN KEY (club_id) REFERENCES clubs (id) ON DELETE CASCADE,
    CONSTRAINT mobile_api_tokens_user_id_foreign FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX mobile_api_tokens_club_user_index ON mobile_api_tokens (club_id, user_id);
CREATE INDEX mobile_api_tokens_user_id_foreign ON mobile_api_tokens (user_id);
COMMENT ON TABLE mobile_api_tokens IS 'Токены мобильных приложений в формате Sanctum (Q-058); id перенесённых = personal_access_tokens.id';
COMMENT ON COLUMN mobile_api_tokens.revoked_at IS 'Выход/смена клуба/сброс пароля: строка остаётся, чтобы токен не ушёл на старый сервер';

-- +goose StatementBegin
CREATE FUNCTION zafiro_current_mobile_token_hash() RETURNS text
    LANGUAGE sql STABLE PARALLEL SAFE AS $$
    SELECT NULLIF(current_setting('app.mobile_token_hash', true), '')
$$;
-- +goose StatementEnd

ALTER TABLE mobile_api_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE mobile_api_tokens FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON mobile_api_tokens USING (club_id = zafiro_current_club_id())
    WITH CHECK (club_id = zafiro_current_club_id());
CREATE POLICY platform_access ON mobile_api_tokens TO zafiro_platform USING (true) WITH CHECK (true);
CREATE POLICY mobile_token_lookup ON mobile_api_tokens FOR SELECT
    USING (token_hash = zafiro_current_mobile_token_hash());
CREATE POLICY mobile_token_owner_read ON mobile_api_tokens FOR SELECT USING (user_id = zafiro_current_user_id());
CREATE POLICY mobile_token_owner_update ON mobile_api_tokens FOR UPDATE USING (user_id = zafiro_current_user_id())
    WITH CHECK (user_id = zafiro_current_user_id());

-- +goose Down

DROP TABLE IF EXISTS mobile_api_tokens;
DROP FUNCTION IF EXISTS zafiro_current_mobile_token_hash();
