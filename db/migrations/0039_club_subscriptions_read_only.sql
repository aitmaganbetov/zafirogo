-- 0039_club_subscriptions_read_only: пул клуба только читает подписку своего клуба (SEC-005, замечание Ш0 к 0035).
--
-- До этой миграции zafiro_app имел на club_subscriptions полный INSERT/UPDATE/DELETE (общий GRANT из 0004): RLS
-- ограничивал его строкой своего клуба, но в ней он мог поменять всё — статус и срок подписки, тариф, а после 0035
-- и индивидуальную скидку (discount_percent / discount_until / discount_note). То есть ошибка или уязвимость в любом
-- обработчике панели клуба давала клубу бесплатную подписку или скидку 100 % на следующий счёт.
--
-- Подписку меняет только платформа: регистрация клуба, кабинет суперадмина (продление, приостановка, тариф, скидка,
-- отметка оплаты счёта) и воркер истечения — все под ролью zafiro_platform (db.InPlatformTx). Панель клуба подписку
-- только читает (проверка активности, экран «Подписка», снимок скидки в счёте) и строку не блокирует: единственность
-- неоплаченного счёта держит частичный уникальный индекс subscription_invoices (GAP-046), а не FOR UPDATE подписки.
-- Поэтому пулу клуба оставлен один SELECT.

-- +goose Up
REVOKE INSERT, UPDATE, DELETE ON club_subscriptions FROM zafiro_app;

-- +goose Down
GRANT INSERT, UPDATE, DELETE ON club_subscriptions TO zafiro_app;
