-- 0035_subscription_invoices: скидка клуба на подписку и счета за подписку (тема Б, docs/upstream-2026-11.md §2 «Б»,
-- §3.3 BR-180…BR-184; колонки реселлера в счёте — тема Д, BR-185, BR-186).
-- Laravel: 2026_11_07_100000_add_discount_to_club_subscriptions_table.php,
-- 2026_11_08_100000_create_subscription_invoices_table.php, 2026_11_18_100000_create_resellers.php (reseller_*).
--
-- Клуб сам выставляет себе счёт (тариф × число ПК × месяцы − скидка), платит по ссылке Kaspi с номером счёта в
-- комментарии; суперадмин, увидев деньги, отмечает счёт оплаченным — подписка продлевается. Номер счёта —
-- «ZF-» + id с нулями до 5 знаков (SubscriptionInvoice::number()), в базе не хранится: id сохраняется при переносе.
--
-- Отличия от Laravel:
--  * price_per_computer, amount, reseller_amount: decimal(12,2) тенге → bigint тиыны (× 100);
--  * reseller_percent decimal(5,2) → reseller_bp integer, базисные пункты (как resellers.commission_bp, 0034);
--  * status — CHECK ('pending', 'paid', 'canceled'); paid_at заполнен тогда и только тогда, когда счёт оплачен;
--    начисление реселлеру (reseller_amount) есть только у оплаченного счёта;
--  * один неоплаченный счёт на клуб — частичный уникальный индекс (GAP-046: в старом проверка exists() под
--    блокировкой строки подписки не спасала клуб без строки подписки);
--  * months — CHECK (1, 3, 6, 12) (SubscriptionInvoice::MONTHS), computers ≥ 1 (BR-180: max(1, число ПК));
--  * RLS как у всех тенантных таблиц + права (SEC-005): пул клуба выставляет счёт и отменяет свой неоплаченный, но
--    не может сделать счёт оплаченным, тронуть закрытый счёт или удалить его — оплату отмечает только пул платформы
--    (суперадмин). Колонки оплаты (paid_at, confirmed_by, period_ends_at, reseller_amount) пулу клуба не даны.

-- +goose Up
ALTER TABLE club_subscriptions ADD COLUMN discount_percent smallint NOT NULL DEFAULT 0;
ALTER TABLE club_subscriptions ADD COLUMN discount_until date;
ALTER TABLE club_subscriptions ADD COLUMN discount_note varchar(200);
ALTER TABLE club_subscriptions ADD CONSTRAINT club_subscriptions_discount_percent_check CHECK (discount_percent BETWEEN 0 AND 100);
COMMENT ON COLUMN club_subscriptions.discount_percent IS
    'Индивидуальная скидка клуба на подписку, целые проценты 0…100; ставит суперадмин (Laravel: 2026_11_07_100000_add_discount_to_club_subscriptions_table)';
COMMENT ON COLUMN club_subscriptions.discount_until IS 'Последний день действия скидки включительно; NULL — бессрочно (BR-181)';
COMMENT ON COLUMN club_subscriptions.discount_note IS 'Причина скидки (видна суперадмину)';

CREATE TABLE subscription_invoices (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id            bigint      NOT NULL,
    saas_plan_id       bigint      NOT NULL,
    months             smallint    NOT NULL,
    computers          integer     NOT NULL,
    price_per_computer bigint      NOT NULL,
    discount_percent   smallint    NOT NULL DEFAULT 0,
    amount             bigint      NOT NULL,
    reseller_id        bigint,
    reseller_bp        integer,
    reseller_amount    bigint,
    status             varchar(16) NOT NULL DEFAULT 'pending',
    created_by         bigint,
    confirmed_by       bigint,
    paid_at            timestamptz,
    period_ends_at     timestamptz,
    created_at         timestamptz,
    updated_at         timestamptz,
    CONSTRAINT subscription_invoices_club_id_foreign FOREIGN KEY (club_id) REFERENCES clubs (id) ON DELETE CASCADE,
    CONSTRAINT subscription_invoices_saas_plan_id_foreign FOREIGN KEY (saas_plan_id) REFERENCES saas_plans (id) ON DELETE RESTRICT,
    CONSTRAINT subscription_invoices_reseller_id_foreign FOREIGN KEY (reseller_id) REFERENCES resellers (id) ON DELETE SET NULL,
    CONSTRAINT subscription_invoices_created_by_foreign FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT subscription_invoices_confirmed_by_foreign FOREIGN KEY (confirmed_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT subscription_invoices_status_check CHECK (status IN ('pending', 'paid', 'canceled')),
    CONSTRAINT subscription_invoices_months_check CHECK (months IN (1, 3, 6, 12)),
    CONSTRAINT subscription_invoices_computers_check CHECK (computers >= 1),
    CONSTRAINT subscription_invoices_price_per_computer_check CHECK (price_per_computer >= 0),
    CONSTRAINT subscription_invoices_discount_percent_check CHECK (discount_percent BETWEEN 0 AND 100),
    CONSTRAINT subscription_invoices_amount_check CHECK (amount >= 0 AND amount % 100 = 0),
    CONSTRAINT subscription_invoices_reseller_bp_check CHECK (reseller_bp BETWEEN 0 AND 10000),
    CONSTRAINT subscription_invoices_reseller_amount_check CHECK (reseller_amount >= 0),
    CONSTRAINT subscription_invoices_paid_check CHECK ((status = 'paid') = (paid_at IS NOT NULL)),
    CONSTRAINT subscription_invoices_earning_check CHECK (reseller_amount IS NULL OR status = 'paid')
);
CREATE INDEX subscription_invoices_club_id_created_at_index ON subscription_invoices (club_id, created_at);
CREATE INDEX subscription_invoices_status_created_at_index ON subscription_invoices (status, created_at);
CREATE INDEX subscription_invoices_reseller_id_status_paid_at_index ON subscription_invoices (reseller_id, status, paid_at);
CREATE INDEX subscription_invoices_saas_plan_id_foreign ON subscription_invoices (saas_plan_id);
CREATE INDEX subscription_invoices_created_by_foreign ON subscription_invoices (created_by);
CREATE INDEX subscription_invoices_confirmed_by_foreign ON subscription_invoices (confirmed_by);
-- GAP-046, BR-184: один неоплаченный счёт на клуб.
CREATE UNIQUE INDEX subscription_invoices_club_id_pending_unique ON subscription_invoices (club_id) WHERE status = 'pending';

COMMENT ON TABLE subscription_invoices IS
    'Счёт клубу за N месяцев тарифа платформы на все ПК клуба: оплата Kaspi, подтверждает суперадмин (Laravel: 2026_11_08_100000_create_subscription_invoices_table). Номер — ZF- + id (5 знаков)';
COMMENT ON COLUMN subscription_invoices.months IS 'Срок: 1, 3, 6 или 12 месяцев (SubscriptionInvoice::MONTHS)';
COMMENT ON COLUMN subscription_invoices.computers IS 'Снимок числа ПК клуба при выставлении, не меньше 1 (BR-180)';
COMMENT ON COLUMN subscription_invoices.price_per_computer IS 'Снимок цены тарифа за ПК в месяц, тиыны (Laravel: decimal(12,2) тенге × 100)';
COMMENT ON COLUMN subscription_invoices.discount_percent IS 'Снимок скидки: большая из скидки клуба и скидки реселлера, целые проценты (BR-181)';
COMMENT ON COLUMN subscription_invoices.amount IS 'К оплате, тиыны; всегда целые тенге — кратно 100 (BR-180; Laravel: decimal(12,2) × 100)';
COMMENT ON COLUMN subscription_invoices.reseller_id IS 'Реселлер клуба при выставлении счёта (если его код действовал); NULL после удаления реселлера';
COMMENT ON COLUMN subscription_invoices.reseller_bp IS
    'Снимок процента реселлера в базисных пунктах: 1235 = 12,35 % (Laravel: reseller_percent decimal(5,2) × 100)';
COMMENT ON COLUMN subscription_invoices.reseller_amount IS
    'Начисление реселлеру при оплате, тиыны (BR-186; Laravel: decimal(12,2) × 100); остаётся после удаления реселлера';
COMMENT ON COLUMN subscription_invoices.status IS 'pending → paid (суперадмин увидел деньги) или canceled';
COMMENT ON COLUMN subscription_invoices.confirmed_by IS 'Суперадмин, отметивший оплату';
COMMENT ON COLUMN subscription_invoices.period_ends_at IS 'До какого момента продлена подписка этой оплатой (BR-183)';

