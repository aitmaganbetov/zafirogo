CREATE POLICY tenant_isolation ON subscription_invoices USING (club_id = zafiro_current_club_id())
    WITH CHECK (club_id = zafiro_current_club_id());
CREATE POLICY platform_access ON subscription_invoices TO zafiro_platform USING (true) WITH CHECK (true);
-- Ограничивающие политики пула клуба (вдобавок к tenant_isolation): новый счёт — только неоплаченный; менять можно
-- только неоплаченный и только оставить его неоплаченным или отменить.
CREATE POLICY app_insert_pending ON subscription_invoices AS RESTRICTIVE FOR INSERT TO zafiro_app
    WITH CHECK (status = 'pending');
CREATE POLICY app_update_pending ON subscription_invoices AS RESTRICTIVE FOR UPDATE TO zafiro_app
    USING (status = 'pending') WITH CHECK (status IN ('pending', 'canceled'));

REVOKE ALL ON subscription_invoices FROM zafiro_app, zafiro_platform;
