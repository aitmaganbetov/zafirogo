-- 0022_api_v1: интеграционный API /api/v1 (Этап 4, блок H1).
--
-- 1. Поиск API-ключа до выбора клуба (решение L-3, docs/open-questions/stage1-ledger.md): узкая политика
--    api_key_lookup — строка api_keys видна роли zafiro_app только в транзакции, где app.api_key_prefix равен её
--    префиксу (как enroll_code_lookup для кодов регистрации, 0009). Префикс публичен (zfk_<8 символов>); сравнение
--    хэша секрета — в приложении за постоянное время (ApiKeyManager::verify()). Остальные строки клуба (членство
--    создателя, подписка) читаются уже под app.club_id ключа.
-- 2. api_request_logs → PARTITION BY RANGE (created_at), месяцы по UTC (решение PD-8, как activity_logs в 0011):
--    старая таблица переименовывается, создаются партиции под весь диапазон данных + 3 месяца, строки переливаются.
--    PK становится (id, created_at). Белый список zafiro_create_monthly_partitions расширен на api_request_logs;
--    новые партиции создаёт db.EnsurePartitions (db.PartitionedTables).

-- +goose Up

-- ---------------------------------------------------------------------------
-- 1. Поиск ключа по префиксу
-- ---------------------------------------------------------------------------

-- +goose StatementBegin
CREATE FUNCTION zafiro_current_api_key_prefix() RETURNS text
    LANGUAGE sql STABLE PARALLEL SAFE AS $$
    SELECT NULLIF(current_setting('app.api_key_prefix', true), '')
$$;
-- +goose StatementEnd

CREATE POLICY api_key_lookup ON api_keys FOR SELECT
    USING (prefix = zafiro_current_api_key_prefix());

