CREATE TABLE api_request_logs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    club_id     bigint,
    api_key_id  bigint,
    key_prefix  varchar(16),
    method      varchar(8) NOT NULL,
    endpoint    varchar(191) NOT NULL,
    status      integer NOT NULL CHECK (status >= 0),
    duration_ms bigint NOT NULL CHECK (duration_ms >= 0),
    ip          varchar(45) NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT api_request_logs_pkey PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);
CREATE INDEX api_request_logs_club_id_created_at_index ON api_request_logs (club_id, created_at);
CREATE INDEX api_request_logs_api_key_id_created_at_index ON api_request_logs (api_key_id, created_at);
CREATE INDEX api_request_logs_created_at_index ON api_request_logs (created_at);
COMMENT ON TABLE api_request_logs IS 'Журнал запросов /api/v1 (LogApiRequest): без query, заголовков и тел. Партиции по месяцам (UTC), 0022';

-- +goose StatementBegin
DO $$
DECLARE
    first_month date;
    last_month  date := date_trunc('month', now() AT TIME ZONE 'UTC')::date + interval '3 months';
    m           date;
BEGIN
    SELECT date_trunc('month', min(created_at) AT TIME ZONE 'UTC')::date INTO first_month
    FROM api_request_logs_unpartitioned;
    m := LEAST(COALESCE(first_month, last_month), date_trunc('month', now() AT TIME ZONE 'UTC')::date);
    WHILE m <= last_month LOOP
        PERFORM zafiro_create_monthly_partitions('api_request_logs', m, 1);
        m := (m + interval '1 month')::date;
    END LOOP;
END
$$;
-- +goose StatementEnd

