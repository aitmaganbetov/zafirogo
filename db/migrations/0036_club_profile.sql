-- 0036_club_profile: город, адрес и профиль клуба, фото клуба, оборудование зон (тема В, docs/upstream-2026-11.md
-- §2 «В»): то, что гостевое приложение показывает в каталоге клубов города и на странице клуба.
-- Laravel: 2026_11_13_100000_add_city_and_address_to_clubs_table.php, 2026_11_14_100000_create_club_profile.php.
--
-- Отличия от Laravel:
--  * clubs.city — ключ App\Support\Cities (25 городов; список — в коде, не в CHECK: он меняется без миграции
--    данных, как в старом). Индекс каталога — (city, name) по клубам с городом вместо индекса по одному city:
--    каталог — «клубы города по имени», клубы без города в нём не участвуют;
--  * clubs.profile, club_zones.devices: json → jsonb, только объект (пустое старый код хранил как NULL);
--  * club_zones.description: varchar(255) → varchar(500) — форма «Зоны и оборудование» старого кода принимает до
--    500 символов (ClubProfileController::updateZone(), max:500), а MySQL при длине > 255 отвечал ошибкой;
--  * club_photos.sort_order: unsignedSmallInteger → integer со знаком: обложка = min(sort_order) − 1
--    (ClubProfileController::coverPhoto()) — в MySQL у первой же обложки при sort_order = 0 это ошибка беззнаковой
--    колонки;
--  * файлы фото — не на локальном диске (storage/app/private/club-photos/<клуб>/<40 символов>.png|jpg|webp), а в
--    club_photo_images (решение UQ-19 — как логотип клуба, 0019, и картинки новостей, 0018: несколько инстансов
--    без общего диска). club_photos.path — прежнего формата: по нему сверяется имя файла в публичном адресе
--    GET /club-photos/{club}/{file} (его кэширует приложение). Фото ≤ 3 МБ (max:3072), PNG, JPEG или WebP;
--  * (club_id, path) уникальны: адрес фото однозначен.

-- +goose Up
ALTER TABLE clubs ADD COLUMN city varchar(32);
ALTER TABLE clubs ADD COLUMN address varchar(255);
ALTER TABLE clubs ADD COLUMN profile jsonb;
ALTER TABLE clubs ADD CONSTRAINT clubs_profile_check CHECK (jsonb_typeof(profile) = 'object');
CREATE INDEX clubs_city_name_index ON clubs (city, name) WHERE city IS NOT NULL;
COMMENT ON COLUMN clubs.city IS
    'Город клуба — ключ списка городов (Laravel: App\Support\Cities, 2026_11_13_100000_add_city_and_address_to_clubs_table); NULL — клуба нет в каталоге приложения';
COMMENT ON COLUMN clubs.address IS 'Адрес клуба для каталога приложения';
COMMENT ON COLUMN clubs.profile IS
    'Профиль клуба для приложения: {description ≤ 2000, phone ≤ 32, hours ≤ 100, instagram ≤ 64 без «@»}; пустой — NULL (Laravel: 2026_11_14_100000_create_club_profile)';

ALTER TABLE club_zones ADD COLUMN devices jsonb;
ALTER TABLE club_zones ADD CONSTRAINT club_zones_devices_check CHECK (jsonb_typeof(devices) = 'object');
ALTER TABLE club_zones ALTER COLUMN description TYPE varchar(500);
COMMENT ON COLUMN club_zones.devices IS
    'Оборудование зоны, заполненное клубом: ключи cpu, gpu, ram, monitor, keyboard, mouse, headset, chair, значения ≤ 120; пустое — NULL (Laravel: 2026_11_14_100000_create_club_profile)';

CREATE TABLE club_photos (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id    bigint       NOT NULL,
    path       varchar(255) NOT NULL,
    sort_order integer      NOT NULL DEFAULT 0,
    created_at timestamptz,
    updated_at timestamptz,
    CONSTRAINT club_photos_club_id_foreign FOREIGN KEY (club_id) REFERENCES clubs (id) ON DELETE CASCADE,
    CONSTRAINT club_photos_club_id_id_unique UNIQUE (club_id, id),
    CONSTRAINT club_photos_club_id_path_unique UNIQUE (club_id, path)
);
CREATE INDEX club_photos_club_id_sort_order_index ON club_photos (club_id, sort_order, id);
COMMENT ON TABLE club_photos IS
    'Фото клуба для гостевого приложения, до 10 на клуб (Laravel: 2026_11_14_100000_create_club_profile); первое по sort_order, id — обложка. Байты — club_photo_images';
COMMENT ON COLUMN club_photos.path IS 'club-photos/<клуб>/<40 символов>.png|jpg|webp — как путь файла в старом коде; имя файла — в публичном адресе фото';
COMMENT ON COLUMN club_photos.sort_order IS 'Порядок показа; обложка = min − 1, поэтому со знаком (Laravel: unsignedSmallInteger)';

CREATE TABLE club_photo_images (
    photo_id     bigint PRIMARY KEY,
    club_id      bigint      NOT NULL,
    content_type varchar(32) NOT NULL,
    data         bytea       NOT NULL,
    created_at   timestamptz NOT NULL,
    CONSTRAINT club_photo_images_photo_fk FOREIGN KEY (club_id, photo_id) REFERENCES club_photos (club_id, id) ON DELETE CASCADE,
    CONSTRAINT club_photo_images_club_id_foreign FOREIGN KEY (club_id) REFERENCES clubs (id) ON DELETE CASCADE,
    CONSTRAINT club_photo_images_content_type_check CHECK (content_type IN ('image/png', 'image/jpeg', 'image/webp')),
    CONSTRAINT club_photo_images_size_check CHECK (octet_length(data) BETWEEN 1 AND 3145728)
);
CREATE INDEX club_photo_images_club_id_index ON club_photo_images (club_id);
COMMENT ON TABLE club_photo_images IS 'Байты фото клуба (PNG, JPEG или WebP ≤ 3 МБ); строка фото — club_photos (UQ-19)';

