COMMENT ON COLUMN activity_logs.details IS 'Суммы внутри — тенге (строка/число), не тиыны';

-- Партиции: от месяца самой старой строки до текущего + 3 (функция берёт не больше 36 месяцев за вызов —
-- поэтому по одному месяцу).
-- +goose StatementBegin
DO $$
DECLARE
    first_month date;
    last_month  date := date_trunc('month', now() AT TIME ZONE 'UTC')::date + interval '3 months';
    m           date;
BEGIN
    SELECT date_trunc('month', min(COALESCE(created_at, updated_at, now())) AT TIME ZONE 'UTC')::date
    INTO first_month FROM activity_logs_unpartitioned;
    m := LEAST(COALESCE(first_month, last_month), date_trunc('month', now() AT TIME ZONE 'UTC')::date);
    WHILE m <= last_month LOOP
        PERFORM zafiro_create_monthly_partitions('activity_logs', m, 1);
        m := (m + interval '1 month')::date;
    END LOOP;
END
$$;
-- +goose StatementEnd

