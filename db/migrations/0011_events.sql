-- 0011_events: журнал действий по месяцам и outbox событий (Этап 2, блок A4 «События»).
--
-- 1. activity_logs → PARTITION BY RANGE (created_at), месяцы по UTC (docs/schema-changes.md §7, L-7).
--    Перевод с сохранением данных: старая таблица переименовывается, создаётся партиционированная с теми же
--    колонками, ограничениями и политиками, создаются партиции под весь диапазон данных + 3 месяца вперёд,
--    строки переливаются, старая таблица удаляется. PK становится (id, created_at) — требование Postgres
--    (на activity_logs никто не ссылается по FK). created_at становится NOT NULL: старые строки без даты
--    (в Laravel их нет — Eloquent ставит timestamps) получают updated_at или время миграции.
--    Индекс activity_logs_club_id_index не переносится: он — префикс (club_id, created_at).
--    Новые партиции создаёт db.EnsurePartitions (фоновая задача, Q-081): белый список функции
--    zafiro_create_monthly_partitions расширен на activity_logs.
-- 2. outbox_events — события домена, записанные в транзакции действия (server/internal/outbox); публикатор
--    переносит их в NATS JetStream (stream zafiro-events, subject club.<id>.<type>, Nats-Msg-Id = event_id)
--    и ставит published_at. Триггер шлёт NOTIFY zafiro_outbox после вставки (доставляется при COMMIT) —
--    публикатор просыпается сразу, а не по интервалу.

