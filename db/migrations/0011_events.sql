CREATE TABLE outbox_events (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    club_id      bigint NOT NULL,
    event_id     uuid NOT NULL DEFAULT gen_random_uuid(),
    type         varchar(64) NOT NULL,
    payload      jsonb NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    published_at timestamptz,
    attempts     integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error   varchar(255),
    CONSTRAINT outbox_events_event_id_unique UNIQUE (event_id),
    CONSTRAINT outbox_events_type_check CHECK (type ~ '^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$'),
    CONSTRAINT outbox_events_payload_object_check CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT outbox_events_club_id_foreign FOREIGN KEY (club_id) REFERENCES clubs (id) ON DELETE CASCADE
);
-- Очередь публикатора: только неопубликованные, по порядку записи.
CREATE INDEX outbox_events_unpublished_index ON outbox_events (id) WHERE published_at IS NULL;
-- Очистка опубликованных по сроку.
CREATE INDEX outbox_events_published_at_index ON outbox_events (published_at) WHERE published_at IS NOT NULL;
CREATE INDEX outbox_events_club_id_created_at_index ON outbox_events (club_id, created_at);
COMMENT ON TABLE outbox_events IS 'Outbox: события, записанные в транзакции действия; публикуются в NATS JetStream (zafiro-events)';
COMMENT ON COLUMN outbox_events.event_id IS 'Id события для получателей и Nats-Msg-Id (дедупликация JetStream)';
COMMENT ON COLUMN outbox_events.payload IS 'Данные события (data). Без секретов; для типов-вебхуков — без персональных данных';

