-- 0034_resellers: реселлеры и выплаты им (тема Д, docs/upstream-2026-11.md §2 «Д», §3.4 BR-185…BR-189).
-- Laravel: database/migrations/2026_11_18_100000_create_resellers.php (resellers, reseller_payouts,
-- clubs.reseller_id / reseller_attached_at; колонки счёта — в 0035).
--
-- Реселлер — аккаунт (users) с записью в resellers: код, процент с оплат клубов, скидка клубам. Создаёт и удаляет
-- суперадмин; клуб один раз вводит код в настройках. Это данные платформы, не клуба: club_id нет.
--
-- Отличия от Laravel:
--  * commission_percent decimal(5,2) → commission_bp integer, базисные пункты (12,35 % = 1235): в деньгах платформы
--    нет float (UQ-7). Имя изменено намеренно: рядом лежит discount_percent в целых процентах, и колонка «percent»
--    со значением 1235 читалась бы как ошибка;
--  * reseller_payouts.amount decimal(12,2) → bigint тиыны (× 100); сумма строго больше нуля (в старом 0.01…);
--  * reseller_payouts.idempotency_key — нового сервера: двойной клик по «Записать выплату» не создаёт вторую
--    выплату (docs/upstream-2026-11.md §3.6; в старом не закрыто). У перенесённых строк — NULL;
--  * код реселлера — только строчные латинские буквы, цифры и дефис (CHECK = правило формы старого кода после
--    mb_strtolower(trim())): уникальность без учёта регистра (Q-025) получается обычным уникальным индексом;
--  * права (SEC-005, 0028): обе таблицы меняет только zafiro_platform (суперадминка, кабинет реселлера). Пул клуба
--    читает одну строку — реселлера своего клуба (RLS club_reseller_read: карточка «Реселлер» настроек и снимок
--    скидки и процента в счёте, 0035); чужих реселлеров и поиск по коду он не видит. Привязку клуба к реселлеру
--    (clubs.reseller_id) пул клуба не меняет — триггер clubs_reseller_guard: код ищет и клуб привязывает пул
--    платформы.

-- +goose Up
CREATE TABLE resellers (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          bigint       NOT NULL,
    code             varchar(32)  NOT NULL,
    name             varchar(120) NOT NULL,
    commission_bp    integer      NOT NULL DEFAULT 0,
    discount_percent smallint     NOT NULL DEFAULT 0,
    is_active        boolean      NOT NULL DEFAULT true,
    created_at       timestamptz,
    updated_at       timestamptz,
    CONSTRAINT resellers_user_id_unique UNIQUE (user_id),
    CONSTRAINT resellers_code_unique UNIQUE (code),
    CONSTRAINT resellers_user_id_foreign FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT resellers_code_check CHECK (code ~ '^[a-z0-9][a-z0-9-]{2,31}$'),
    CONSTRAINT resellers_commission_bp_check CHECK (commission_bp BETWEEN 0 AND 10000),
    CONSTRAINT resellers_discount_percent_check CHECK (discount_percent BETWEEN 0 AND 100)
);
COMMENT ON TABLE resellers IS
    'Реселлер платформы: аккаунт, код для клубов, процент с оплат и скидка клубам (Laravel: 2026_11_18_100000_create_resellers)';
COMMENT ON COLUMN resellers.code IS 'Код, который клуб вводит в настройках: строчные латинские буквы, цифры, дефис; 3…32 знака';
COMMENT ON COLUMN resellers.commission_bp IS
    'Процент реселлера с оплаты счёта в базисных пунктах: 1235 = 12,35 % (Laravel: commission_percent decimal(5,2) × 100)';
COMMENT ON COLUMN resellers.discount_percent IS 'Скидка клубам реселлера, целые проценты 0…100 (BR-181: берётся большая из скидок)';
COMMENT ON COLUMN resellers.is_active IS 'Код действует: остановленный реселлер не даёт скидки и процента в новых счетах';

CREATE TABLE reseller_payouts (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reseller_id     bigint NOT NULL,
    amount          bigint NOT NULL,
    note            varchar(255),
    created_by      bigint,
    idempotency_key varchar(200),
    created_at      timestamptz,
    updated_at      timestamptz,
    CONSTRAINT reseller_payouts_reseller_id_foreign FOREIGN KEY (reseller_id) REFERENCES resellers (id) ON DELETE CASCADE,
    CONSTRAINT reseller_payouts_created_by_foreign FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT reseller_payouts_amount_check CHECK (amount > 0),
    CONSTRAINT reseller_payouts_idempotency_key_check CHECK (idempotency_key IS NULL OR length(idempotency_key) > 0)
);
CREATE INDEX reseller_payouts_reseller_id_created_at_index ON reseller_payouts (reseller_id, created_at);
CREATE INDEX reseller_payouts_created_by_foreign ON reseller_payouts (created_by);
CREATE UNIQUE INDEX reseller_payouts_idempotency_key_unique ON reseller_payouts (idempotency_key)
    WHERE idempotency_key IS NOT NULL;
COMMENT ON TABLE reseller_payouts IS
    'Выплата реселлеру, записанная суперадмином (Laravel: 2026_11_18_100000_create_resellers). Удаляется вместе с реселлером; сумма остаётся в platform_money_log';
COMMENT ON COLUMN reseller_payouts.amount IS 'Сумма выплаты в тиынах (Laravel: decimal(12,2) тенге × 100)';
COMMENT ON COLUMN reseller_payouts.idempotency_key IS
    'Ключ идемпотентности формы суперадмина (нового сервера): повтор запроса не создаёт вторую выплату; NULL — перенесено из MySQL';

ALTER TABLE clubs ADD COLUMN reseller_id bigint;
ALTER TABLE clubs ADD COLUMN reseller_attached_at timestamptz;
ALTER TABLE clubs ADD CONSTRAINT clubs_reseller_id_foreign FOREIGN KEY (reseller_id) REFERENCES resellers (id) ON DELETE SET NULL;
CREATE INDEX clubs_reseller_id_foreign ON clubs (reseller_id) WHERE reseller_id IS NOT NULL;
COMMENT ON COLUMN clubs.reseller_id IS
    'Реселлер клуба (код введён в настройках один раз; сменить — суперадмин). Меняет только пул платформы (clubs_reseller_guard)';
COMMENT ON COLUMN clubs.reseller_attached_at IS 'Когда клуб привязан к реселлеру';

-- Привязка клуба к реселлеру — деньги платформы (скидка в счёте, процент реселлеру). У пула клуба UPDATE на всю
-- строку своего клуба (0028), поэтому колонки закрывает триггер: менять их может только роль с членством в
-- zafiro_platform (суперадминка и настройки клуба через пул платформы) и владелец схемы (миграции, перенос).
-- +goose StatementBegin
CREATE FUNCTION zafiro_clubs_reseller_guard() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF (NEW.reseller_id IS DISTINCT FROM OLD.reseller_id OR NEW.reseller_attached_at IS DISTINCT FROM OLD.reseller_attached_at)
       AND pg_has_role(current_user, 'zafiro_app', 'MEMBER')
       AND NOT pg_has_role(current_user, 'zafiro_platform', 'MEMBER') THEN
        RAISE EXCEPTION 'clubs.reseller_id: only zafiro_platform changes the reseller of a club'
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END
$$;
-- +goose StatementEnd
CREATE TRIGGER clubs_reseller_guard BEFORE UPDATE OF reseller_id, reseller_attached_at ON clubs
    FOR EACH ROW EXECUTE FUNCTION zafiro_clubs_reseller_guard();

-- resellers: без FORCE (как clubs, 0028) — владелец схемы (миграции, перенос, удаление аккаунтов) не ограничен.
ALTER TABLE resellers ENABLE ROW LEVEL SECURITY;
CREATE POLICY club_reseller_read ON resellers FOR SELECT TO zafiro_app
    USING (id = (SELECT c.reseller_id FROM clubs c WHERE c.id = zafiro_current_club_id()));
CREATE POLICY platform_access ON resellers TO zafiro_platform USING (true) WITH CHECK (true);

REVOKE ALL ON resellers, reseller_payouts FROM zafiro_app, zafiro_platform;
GRANT SELECT ON resellers TO zafiro_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON resellers TO zafiro_platform;
-- Выплата не исправляется и не удаляется сама (BR-188) — только каскадом при удалении реселлера.
GRANT SELECT, INSERT ON reseller_payouts TO zafiro_platform;
REVOKE ALL ON SEQUENCE resellers_id_seq, reseller_payouts_id_seq FROM zafiro_app;

-- +goose Down
DROP TRIGGER IF EXISTS clubs_reseller_guard ON clubs;
DROP FUNCTION IF EXISTS zafiro_clubs_reseller_guard();
-- Политика чтения реселлера своего клуба ссылается на clubs.reseller_id — сначала она.
DROP POLICY IF EXISTS club_reseller_read ON resellers;
DROP INDEX IF EXISTS clubs_reseller_id_foreign;
ALTER TABLE clubs DROP CONSTRAINT IF EXISTS clubs_reseller_id_foreign;
ALTER TABLE clubs DROP COLUMN IF EXISTS reseller_attached_at;
ALTER TABLE clubs DROP COLUMN IF EXISTS reseller_id;
DROP TABLE IF EXISTS reseller_payouts;
DROP TABLE IF EXISTS resellers;
