-- Этап 7: история проблем здоровья ПК (docs/open-questions/stage7-health.md). В старом Laravel этого нет — новая
-- функция по поручению владельца: администратор клуба видит загрузку и здоровье своих ПК.
--
-- Измерения агента (Status.health) живут только в снимке присутствия (Valkey) — в Postgres не пишется каждый Status
-- (CLAUDE.md «Производительность»). Здесь — только ПЕРЕХОДЫ подтверждённых проблем (server/internal/agent/health):
-- строка вставляется, когда проблема продержалась agent.health.raise_after, и закрывается (cleared_at), когда её не
-- было agent.health.clear_after. Открытая проблема одного вида у ПК одна (вставка — INSERT … WHERE NOT EXISTS;
-- уникальный индекс на партиционированной таблице обязан включать raised_at и не помог бы).
--
-- * Тенантность: club_id + RLS tenant_isolation (как 0004), запросы sqlc фильтруют по club_id.
-- * Партиции по месяцам raised_at (UTC), как api_request_logs (0022): создаёт db.EnsurePartitions, удаляет по сроку
--   agent.health.event_retention задача logs:retention (db.RetentionTables, белые списки функций ниже).
--   Проблема, открытая дольше срока, уходит вместе со своей партицией — на ПК в сети она будет записана снова.
-- * Права: пул клуба zafiro_app — чтение, вставка и закрытие (UPDATE только cleared_at); удалять строки журнала не
--   может (только DROP партиции по сроку, функция SECURITY DEFINER от платформы). zafiro_platform — только чтение.

-- +goose Up
CREATE TABLE computer_health_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    club_id     bigint      NOT NULL REFERENCES clubs (id) ON DELETE CASCADE,
    computer_id bigint      NOT NULL REFERENCES club_computers (id) ON DELETE CASCADE,
    kind        varchar(32) NOT NULL CONSTRAINT computer_health_events_kind_check
        CHECK (kind IN ('cpu_hot', 'gpu_hot', 'disk_low', 'disk_smart', 'mouse', 'keyboard', 'monitor',
                        'network_slow', 'unstable')),
    raised_at   timestamptz NOT NULL,
    cleared_at  timestamptz CONSTRAINT computer_health_events_cleared_check CHECK (cleared_at >= raised_at),
    details     jsonb       NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT computer_health_events_pkey PRIMARY KEY (id, raised_at)
) PARTITION BY RANGE (raised_at);

-- История ПК в карточке: keyset (raised_at DESC, id DESC) внутри клуба и ПК.
CREATE INDEX computer_health_events_history_index ON computer_health_events (club_id, computer_id, raised_at DESC, id DESC);
-- Открытые проблемы ПК (восстановление при подключении, закрытие).
CREATE INDEX computer_health_events_open_index ON computer_health_events (club_id, computer_id, kind)
    WHERE cleared_at IS NULL;

COMMENT ON TABLE computer_health_events IS
    'Переходы проблем здоровья ПК (появилась/ушла), не каждый Status. Партиции по месяцам raised_at (UTC), 0030';
COMMENT ON COLUMN computer_health_events.details IS
    'Подробности на момент появления: температура, диски, скорость сети, счётчики сбоев (без секретов и персональных данных)';

ALTER TABLE computer_health_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE computer_health_events FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON computer_health_events USING (club_id = zafiro_current_club_id())
    WITH CHECK (club_id = zafiro_current_club_id());
CREATE POLICY platform_access ON computer_health_events TO zafiro_platform USING (true) WITH CHECK (true);

REVOKE ALL ON computer_health_events FROM zafiro_app, zafiro_platform;
GRANT SELECT, INSERT ON computer_health_events TO zafiro_app;
GRANT UPDATE (cleared_at) ON computer_health_events TO zafiro_app;
GRANT SELECT ON computer_health_events TO zafiro_platform;
GRANT USAGE ON SEQUENCE computer_health_events_id_seq TO zafiro_app;
REVOKE ALL ON SEQUENCE computer_health_events_id_seq FROM zafiro_platform;

-- Белые списки функций партиций (CREATE OR REPLACE сохраняет владельца и права: EXECUTE — только zafiro_platform).
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION zafiro_create_monthly_partitions(p_parent text, p_from date, p_months integer)
    RETURNS integer
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE
    month_start date;
    part_name text;
    created integer := 0;
    grantee text;
BEGIN
    IF p_parent NOT IN ('ledger_transactions', 'ledger_entries', 'ledger_minute_entries', 'audit_log',
                        'activity_logs', 'api_request_logs', 'computer_health_events') THEN
        RAISE EXCEPTION 'zafiro_create_monthly_partitions: % is not a monthly partitioned table', p_parent;
    END IF;
    IF p_months < 1 OR p_months > 36 THEN
        RAISE EXCEPTION 'zafiro_create_monthly_partitions: months must be 1..36, got %', p_months;
    END IF;
    month_start := date_trunc('month', p_from)::date;
    FOR i IN 1..p_months LOOP
        part_name := p_parent || '_' || to_char(month_start, 'YYYY_MM');
        IF to_regclass('public.' || quote_ident(part_name)) IS NULL THEN
            EXECUTE format('CREATE TABLE public.%I PARTITION OF public.%I FOR VALUES FROM (%L) TO (%L)',
                           part_name, p_parent,
                           month_start::timestamp AT TIME ZONE 'UTC',
                           (month_start + 1 * interval '1 month')::timestamp AT TIME ZONE 'UTC');
            FOR grantee IN SELECT r.rolname FROM pg_roles r WHERE r.rolname IN ('zafiro_app', 'zafiro_platform') LOOP
                EXECUTE format('REVOKE ALL ON public.%I FROM %I', part_name, grantee);
            END LOOP;
            EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC', part_name);
            created := created + 1;
        END IF;
        month_start := (month_start + interval '1 month')::date;
    END LOOP;
    RETURN created;
END
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION zafiro_drop_monthly_partitions(p_parent text, p_before timestamptz)
    RETURNS integer
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE
    part record;
    month_start date;
    dropped integer := 0;
BEGIN
    IF p_parent NOT IN ('api_request_logs', 'computer_health_events') THEN
        RAISE EXCEPTION 'zafiro_drop_monthly_partitions: % has no retention period', p_parent;
    END IF;
    FOR part IN
        SELECT c.relname
        FROM pg_inherits i
        JOIN pg_class c ON c.oid = i.inhrelid
        WHERE i.inhparent = ('public.' || quote_ident(p_parent))::regclass
          AND c.relname ~ ('^' || p_parent || '_[0-9]{4}_[0-9]{2}$')
        ORDER BY c.relname
    LOOP
        month_start := to_date(right(part.relname, 7), 'YYYY_MM');
        -- Партиция [month_start, month_start + 1 месяц) в UTC (zafiro_create_monthly_partitions).
        IF ((month_start + interval '1 month')::timestamp AT TIME ZONE 'UTC') <= p_before THEN
            EXECUTE format('ALTER TABLE public.%I DETACH PARTITION public.%I', p_parent, part.relname);
            EXECUTE format('DROP TABLE public.%I', part.relname);
            dropped := dropped + 1;
        END IF;
    END LOOP;
    RETURN dropped;
END
$$;
-- +goose StatementEnd

